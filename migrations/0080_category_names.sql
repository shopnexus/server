-- Category names in languages other than Vietnamese (2026-11-23). The
-- Vietnamese name stays categories.display_name: embeddings, the search
-- prompt and the search history read it. A language is rows, not a column.

CREATE TABLE category_names (
    code   text NOT NULL REFERENCES categories (code) ON DELETE CASCADE,
    locale text NOT NULL CHECK (locale <> 'vi'),
    name   text NOT NULL CHECK (name <> ''),
    PRIMARY KEY (code, locale)
);

